// Logical Operator

#include <stdio.h>

int main()
{
    int a = 25, b = 5;

    // using operators and printing results
    printf("a && b : %d\n", a && b); // Logical AND
    printf("a || b : %d\n", a || b); // Logical OR
    printf("!a: %d\n", !a);          // Logical NOT

    return 0;
}